  PLUGIN_NOT_FOUND = 0x6a14,
  PLUGIN_SECURITY_PROFILE_MISMATCH = 0x6a15,
  SERVICE_NOT_SUPPORTED = 0x6a16,
  ACTIVE_ANCHOR_CANNOT_BE_DELETED = 0x6a17,
  RESOURCE_IN_USE = 0x6a18,
  RESOURCE_DEPRECATED = 0x6a19,
  PLUGIN_CODE_HASH_MISMATCH = 0x6a1a,
  INVALID_NDEF_PROVIDER = 0x6a1b,

  STORAGE_QUOTA_EXCEEDED = 0x6a20,
  STORAGE_BLOCK_EXHAUSTED = 0x6a21,
  STORAGE_LEASE_NOT_FOUND = 0x6a22,
  STORAGE_SHRINK_BELOW_ALLOCATED = 0x6a23,
  STORAGE_BLOCK_CORRUPTED = 0x6a24,

  CRYPTO_ALGORITHM_NOT_FOUND = 0x6a30,
